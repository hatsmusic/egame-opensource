/**
 * egame-opensource / e2e.js
 * End-to-end encryption for direct messages and group chats.
 *
 * MIT License. See LICENSE for details.
 *
 * Cryptography:
 *   - Key agreement: ECDH over the P-256 curve (WebCrypto)
 *   - Message encryption: AES-GCM with 256-bit keys
 *   - Private keys are generated on-device and stored in localStorage;
 *     they never leave the device.
 *
 * Two conversation types:
 *
 * 1) Direct messages (DM): each message is encrypted with a key derived
 *    from ECDH(myPrivateKey, theirPublicKey). Both sides derive the same
 *    shared secret independently — no key exchange round-trip needed.
 *
 * 2) Group chats: a symmetric group key (AES-GCM) is generated by the
 *    group creator and "wrapped" (encrypted) individually for each member
 *    using ECDH-derived keys. Members unwrap it with their own private key.
 *
 * Multi-key support (Telegram-inspired): group messages carry the key_id
 * they were encrypted with (kid), so the receiver looks up THAT exact key
 * instead of guessing "the latest". Multiple keys can exist after client
 * races or WebView reloads (in-memory caches wiped), which previously
 * caused intermittent decrypt failures.
 *
 * Requires: a browser (or runtime) with WebCrypto (crypto.subtle).
 */

// E2E encryption: ECDH P-256 + AES-GCM. Private key in localStorage, never leaves device.
const E2E = (() => {
  const LS_KEY = 'e2e_privkey';
  let keyPair = null;

  const b64 = (buf) => btoa(String.fromCharCode(...new Uint8Array(buf)));
  const unb64 = (s) => Uint8Array.from(atob(s), c => c.charCodeAt(0));

  // Load existing key pair from localStorage, or generate a new one.
  async function ensureKeys() {
    if (keyPair) return keyPair;
    try {
      const saved = localStorage.getItem(LS_KEY);
      if (saved) {
        const jwk = JSON.parse(saved);
        const priv = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveKey']);
        const pubJwk = { kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y, ext: true };
        keyPair = { priv, pubJwk };
        return keyPair;
      }
    } catch {}
    // Generate new
    const kp = await crypto.subtle.generateKey({ name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveKey']);
    const privJwk = await crypto.subtle.exportKey('jwk', kp.privateKey);
    const pubJwk = await crypto.subtle.exportKey('jwk', kp.publicKey);
    try { localStorage.setItem(LS_KEY, JSON.stringify(privJwk)); } catch {}
    keyPair = { priv: kp.privateKey, pubJwk };
    return keyPair;
  }

  // Get our public key (JWK) to share with contacts / publish on the server.
  async function getPublicJwk() {
    const { pubJwk } = await ensureKeys();
    return pubJwk;
  }

  // Export the raw stored private key JWK string (for backup / device migration).
  async function exportPrivate() {
    const saved = localStorage.getItem(LS_KEY);
    return saved || null;
  }

  // Import a private key JWK string (restores the same identity on a new device).
  async function importPrivate(jwkStr) {
    const jwk = JSON.parse(jwkStr);
    const priv = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDH', namedCurve: 'P-256' }, true, ['deriveKey']);
    localStorage.setItem(LS_KEY, JSON.stringify(jwk));
    const pubJwk = { kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y, ext: true };
    keyPair = { priv, pubJwk };
    return pubJwk;
  }

  // Derive the shared AES-GCM key from our private key + their public JWK.
  async function sharedKey(theirJwk) {
    const { priv } = await ensureKeys();
    const theirPub = await crypto.subtle.importKey('jwk', theirJwk, { name: 'ECDH', namedCurve: 'P-256' }, true, []);
    return crypto.subtle.deriveKey(
      { name: 'ECDH', public: theirPub },
      priv,
      { name: 'AES-GCM', length: 256 },
      false, ['encrypt', 'decrypt']
    );
  }

  // DM: encrypt with the ECDH-derived key. Returns { iv, ct } as base64.
  async function encryptDM(theirJwk, plaintext) {
    const key = await sharedKey(theirJwk);
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(plaintext));
    return { iv: b64(iv), ct: b64(ct) };
  }

  // DM: decrypt with the ECDH-derived key. Throws if the key is wrong.
  async function decryptDM(theirJwk, ivB64, ctB64) {
    const key = await sharedKey(theirJwk);
    const pt = await crypto.subtle.decrypt(
      { name: 'AES-GCM', iv: unb64(ivB64) }, key, unb64(ctB64));
    return new TextDecoder().decode(pt);
  }

  // Group: generate a fresh symmetric group key (AES-GCM 256-bit).
  async function genGroupKey() {
    return crypto.subtle.generateKey({ name: 'AES-GCM', length: 256 }, true, ['encrypt', 'decrypt']);
  }

  // Group: wrap (encrypt) the group key for one member using ECDH.
  // Returns { iv, ct, senderPub } — the member unwraps it with unwrapGroupKey.
  async function wrapGroupKey(groupKey, theirJwk) {
    const wrapKey = await sharedKey(theirJwk);
    const { pubJwk } = await ensureKeys();
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const raw = await crypto.subtle.exportKey('raw', groupKey);
    const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, wrapKey, raw);
    return { iv: b64(iv), ct: b64(ct), senderPub: pubJwk };
  }

  // Group: unwrap a wrapped group key (wrapped = { iv, ct, senderPub }).
  // The shared secret is ECDH(myPrivateKey, senderPublicKey).
  async function unwrapGroupKey(wrapped) {
    const { priv } = await ensureKeys();
    const senderPub = await crypto.subtle.importKey('jwk', wrapped.senderPub, { name: 'ECDH', namedCurve: 'P-256' }, true, []);
    const wrapKey = await crypto.subtle.deriveKey({ name: 'ECDH', public: senderPub }, priv,
      { name: 'AES-GCM', length: 256 }, false, ['decrypt']);
    const raw = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: unb64(wrapped.iv) }, wrapKey, unb64(wrapped.ct));
    return crypto.subtle.importKey('raw', raw, { name: 'AES-GCM' }, true, ['encrypt', 'decrypt']);
  }

  // Group: encrypt a message with the symmetric group key.
  async function encryptGroup(groupKey, plaintext) {
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, groupKey, new TextEncoder().encode(plaintext));
    return { iv: b64(iv), ct: b64(ct) };
  }

  // Group: decrypt a message with the symmetric group key. Throws if wrong key.
  async function decryptGroup(groupKey, ivB64, ctB64) {
    const pt = await crypto.subtle.decrypt({ name: 'AES-GCM', iv: unb64(ivB64) }, groupKey, unb64(ctB64));
    return new TextDecoder().decode(pt);
  }

  // Pack/unpack an encrypted payload for storage/transmission (JSON string).
  // Group messages carry the key_id (kid) they were encrypted with so the
  // receiver fetches THAT exact key instead of assuming "the latest".
  function pack(enc, kid) { return JSON.stringify(kid ? { enc: 1, kid, ...enc } : { enc: 1, ...enc }); }
  function isPacked(content) {
    try { const o = JSON.parse(content); return o && o.enc === 1 ? o : null; }
    catch { return null; }
  }

  return {
    ensureKeys, getPublicJwk, exportPrivate, importPrivate,
    encryptDM, decryptDM, genGroupKey, wrapGroupKey, unwrapGroupKey,
    encryptGroup, decryptGroup, pack, isPacked,
  };
})();

// Export for bundlers / Node test harnesses; harmless in browsers.
if (typeof module !== 'undefined' && module.exports) module.exports = E2E;
